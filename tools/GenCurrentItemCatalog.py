# -*- coding: utf-8 -*-
"""Generate native/AegisCoach.Native/Data/CurrentItemCatalog.cs from d2vpkr game files.

Usage:
    python tools/GenCurrentItemCatalog.py <shops.txt> <neutral_items.txt> <out.cs>

The .txt inputs are the current-patch game files from dotabuff/d2vpkr:
    dota/scripts/npc/shops.txt
    dota/scripts/npc/neutral_items.txt
"""

import re
import sys


def parse_blocks(raw: str):
    raw = re.sub(r"//[^\r\n]*", "", raw)
    blocks = {}
    pat = re.compile(r'"([a-z0-9_]+)"\s*\r?\n\s*\{')
    for m in pat.finditer(raw):
        name = m.group(1)
        start = m.end()
        depth = 1
        i = start
        while depth > 0 and i < len(raw):
            ch = raw[i]
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
            i += 1
        blocks[name] = raw[start : i - 1]
    return blocks


def main() -> None:
    shops_path, neutral_path, out_path = sys.argv[1:4]

    tabs = parse_blocks(open(shops_path, encoding="utf-8").read())
    event_tabs = {"diretide2020_pregame", "nemestice_pregame", "winter2022_pregame"}
    shop = set()
    for tab, body in tabs.items():
        if tab in event_tabs or tab == "dota_shops":
            continue
        for it in re.findall(r'"item"\s+"(item_[a-z0-9_]+)"', body):
            shop.add(it)
    shop |= {
        "item_ward_dispenser",
        "item_courier",
        "item_flying_courier",
        "item_famango",
        "item_great_famango",
        "item_greater_famango",
        "item_tome_of_knowledge",
        "item_refresher_shard",
    }

    neutral_raw = open(neutral_path, encoding="utf-8").read()
    neutral = {name.strip('"') for name in re.findall(r'"item_[a-z0-9_]+"', neutral_raw)}
    tier_map = {}
    for tm in re.finditer(r'"(\d)"\s*\r?\n\s*\{([^{}]*)"items"\s*\{([^{}]*)\}', neutral_raw):
        tier = int(tm.group(1))
        for m in re.finditer(r'"item_[a-z0-9_]+"', tm.group(3)):
            tier_map[m.group(0).strip('"')] = tier

    special_set = {
        "item_aegis",
        "item_cheese",
        "item_roshans_banner",
        "item_travel_boots_2",
        "item_ultimate_scepter_2",
        "item_ultimate_scepter_roshan",
        "item_aghanims_shard_roshan",
    }

    q = '"'
    lines = []
    lines.append("// <auto-generated>")
    lines.append("// Current-patch (7.41e) item catalog, generated from d2vpkr game files")
    lines.append("// (dota/scripts/npc/shops.txt + neutral_items.txt). Regenerate after patches.")
    lines.append("// </auto-generated>")
    lines.append("")
    lines.append("using System;")
    lines.append("using System.Collections.Generic;")
    lines.append("")
    lines.append("namespace AegisCoach.Native.Data;")
    lines.append("")
    lines.append("public static class CurrentItemCatalog")
    lines.append("{")
    lines.append("    /// <summary>Items buyable in the current-patch shop.</summary>")
    lines.append("    public static readonly HashSet<string> ShopItems = new(StringComparer.OrdinalIgnoreCase)")
    lines.append("    {")
    for it in sorted(shop):
        lines.append("        " + q + it + q + ",")
    lines.append("    };")
    lines.append("")
    lines.append("    /// <summary>Current neutral items (trinkets/enchantments); value = tier (enchantments 0).</summary>")
    lines.append("    public static readonly Dictionary<string, int> NeutralItems = new(StringComparer.OrdinalIgnoreCase)")
    lines.append("    {")
    for it in sorted(neutral):
        lines.append("        [" + q + it + q + "] = " + str(tier_map.get(it, 0)) + ",")
    lines.append("    };")
    lines.append("")
    lines.append("    /// <summary>Current special items (Roshan drops/upgrades/special consumables).</summary>")
    lines.append("    public static readonly HashSet<string> SpecialItems = new(StringComparer.OrdinalIgnoreCase)")
    lines.append("    {")
    for it in sorted(special_set):
        lines.append("        " + q + it + q + ",")
    lines.append("    };")
    lines.append("")
    lines.append("    public static bool IsShopItem(string name) => ShopItems.Contains(name);")
    lines.append("")
    lines.append("    public static bool IsNeutralItem(string name) => NeutralItems.ContainsKey(name);")
    lines.append("")
    lines.append("    public static bool IsSpecialItem(string name) => SpecialItems.Contains(name);")
    lines.append("")
    lines.append("    public static bool IsCurrent(string name) => ShopItems.Contains(name) || NeutralItems.ContainsKey(name) || SpecialItems.Contains(name);")
    lines.append("")
    lines.append("    public static int NeutralTier(string name) => NeutralItems.GetValueOrDefault(name);")
    lines.append("}")
    lines.append("")

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print("written shop=%d neutral=%d special=%d -> %s" % (len(shop), len(neutral), len(special_set), out_path))


if __name__ == "__main__":
    main()
