    public static string GetChineseName(int id, string? fallback = null)
    {
        if (IdToChinese.TryGetValue(id, out var name) && !string.IsNullOrWhiteSpace(name)) return name;
        return !string.IsNullOrWhiteSpace(fallback) ? fallback : ("英雄 #" + id);
    }

    public static string GetChineseName(string? heroName, string? fallback = null)
    {
        if (string.IsNullOrWhiteSpace(heroName)) return fallback ?? string.Empty;
        if (NameToChinese.TryGetValue(heroName, out var name) && !string.IsNullOrWhiteSpace(name)) return name;
        return fallback ?? heroName;
    }
