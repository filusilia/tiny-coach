/**
 * 获取物品的官方商店子分类
 */
export function getItemCategory(name: string): string {
  const key = normalizeItemKey(name)
  if (isNeutralItem(key)) return '中立物品'
  if (SPECIAL_ITEMS.has(key)) return '肉山特殊'
  return CATEGORY_MAP[key] || '军备'
}
